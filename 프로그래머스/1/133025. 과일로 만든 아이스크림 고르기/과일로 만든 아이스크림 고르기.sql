WITH ORDER_3000_UP AS (
    SELECT
        *
    FROM FIRST_HALF
    WHERE
        1=1
        AND TOTAL_ORDER > 3000
), TYPE_FRUIT AS (
    SELECT
        *
    FROM ICECREAM_INFO
    WHERE
        1=1
        AND INGREDIENT_TYPE = 'fruit_based'
)
SELECT
    O3U.FLAVOR
FROM ORDER_3000_UP AS O3U
INNER JOIN TYPE_FRUIT AS TF
ON O3U.FLAVOR = TF.FLAVOR
ORDER BY
    O3U.TOTAL_ORDER DESC


































