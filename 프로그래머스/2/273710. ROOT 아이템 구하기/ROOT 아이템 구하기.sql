WITH ROOT AS (
    SELECT
        ITEM_ID
    FROM ITEM_TREE
    WHERE
        1=1
        AND PARENT_ITEM_ID IS NULL
)
SELECT
    I.ITEM_ID,
    I.ITEM_NAME
FROM ITEM_INFO AS I
INNER JOIN ROOT AS R
ON I.ITEM_ID = R.ITEM_ID
ORDER BY
    I.ITEM_ID
    
    
    

    
    
    



